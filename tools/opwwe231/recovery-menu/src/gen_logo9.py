#!/usr/bin/env python3
"""Generate logo9.h (the apple and the wordmark, both resampled) with the macOS `sips` tool.
Usage: python3 -I gen_logo9.py <avatar png> <wordmark png> <out logo9.h> [apple px (56)] [wordmark width px (100)]
The PNGs are opaque with a near-black background; the same background removal as the v1..v6 menu is baked in here
(channel values up to 24 become black, the rest is stretched), and a pixel that ends up 0x000000 is transparent."""
import os, struct, subprocess, sys, tempfile

def load(png, w, h):
    with tempfile.TemporaryDirectory() as d:
        src = os.path.join(d, "a.bmp")
        cmd = ["sips", "-s", "format", "bmp", "-z", str(h), str(w), png, "--out", src]
        subprocess.run(cmd, check=True, capture_output=True)
        b = open(src, "rb").read()
    off = struct.unpack_from("<I", b, 10)[0]
    w, h, _, bpp = struct.unpack_from("<iiHH", b, 18)
    top_down, h, bp = h < 0, abs(h), bpp // 8
    stride = (w * bp + 3) & ~3
    out = []
    for y in range(h):
        row = y if top_down else h - 1 - y
        for x in range(w):
            p = b[off + row * stride + x * bp: off + row * stride + x * bp + 3]
            c = [(v - 24) * 255 // 231 if v > 24 else 0 for v in (p[2], p[1], p[0])]
            out.append(c[0] << 16 | c[1] << 8 | c[2])
    return w, h, out

avatar, word, dst = sys.argv[1:4]
apple_px = int(sys.argv[4]) if len(sys.argv) > 4 else 56
word_w = int(sys.argv[5]) if len(sys.argv) > 5 else 100
word_h = round(word_w * 36 / 166)  # the wordmark source is 166x36
with open(dst, "w") as f:
    f.write("/* generated by gen_logo9.py: 0xRRGGBB, 0 = transparent */\n")
    for name, png, ww, hh in (("apple", avatar, apple_px, apple_px), ("word", word, word_w, word_h)):
        w, h, px = load(png, ww, hh)
        f.write(f"#define {name.upper()}_W {w}\n#define {name.upper()}_H {h}\nstatic const unsigned int {name}_px[] = {{\n")
        for i in range(0, len(px), 9):
            f.write(", ".join(f"0x{v:06x}" for v in px[i:i + 9]) + ",\n")
        f.write("};\n")
        print(name, w, h)
