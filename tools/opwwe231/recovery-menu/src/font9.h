static void rect(int x, int y, int w, int h, uint32_t c) {
    for (int j = y; j < y + h && j < H; j++)
        for (int i = x; i < x + w && i < W; i++)
            if (i >= 0 && j >= 0) fb[j * pitch_px + i] = PIX(c);
}

static void rrect(int x, int y, int w, int h, int r, uint32_t c) {
    for (int j = 0; j < h; j++) {
        int dy = j < r ? r - j : (j >= h - r ? j - (h - r - 1) : 0), inset = 0;
        if (dy > 0) inset = r - (int)(sqrtf((float)(r * r - (dy - 1) * (dy - 1))) + 0.5f);
        rect(x + inset, y + j, w - 2 * inset, 1, c);
    }
}

static int text_w(const char *s, int sc) { return (int)strlen(s) * 6 * sc - sc; }

static const struct glyph *glyph(char c) { /* upper case only; a character missing from the font shows as '?' */
    const struct glyph *q = 0;
    for (unsigned g = 0; g < sizeof font / sizeof *font; g++) {
        if (font[g].c == c) return &font[g];
        if (font[g].c == '?') q = &font[g];
    }
    return q;
}

static void text_left(const char *s, int x, int cy, int sc, uint32_t col) {
    int y = cy - 7 * sc / 2;
    for (; *s; s++, x += 6 * sc) {
        const struct glyph *g = glyph(*s);
        for (int r = 0; r < 7; r++)
            for (int b = 0; b < 5; b++)
                if (g->r[r] & (0x10 >> b)) rect(x + b * sc, y + r * sc, sc, sc, col);
    }
}

static void text(const char *s, int cx, int cy, int sc, uint32_t col) { text_left(s, cx - text_w(s, sc) / 2, cy, sc, col); }

/* premultiplied 0xRRGGBB, 0 = transparent (see logo9.h) */
static void blit(const unsigned *px, int w, int h, int x0, int y0) {
    for (int j = 0; j < h; j++)
        for (int i = 0; i < w; i++)
            if (px[j * w + i]) fb[(y0 + j) * pitch_px + x0 + i] = PIX(px[j * w + i]);
}

